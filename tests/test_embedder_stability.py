def synthetic_image_array() -> np.ndarray:
    """A deterministic 256x256 RGB test pattern, built from integers only.

    Three independent structures so the embedding is not degenerate: a
    horizontal ramp, a vertical ramp, an XOR interference field, plus a 32px
    checkerboard and a per-pixel LCG dither. The dither matters — a smooth
    gradient alone is nearly scale-invariant, which is exactly the signal a
    changed resize filter would destroy without changing the vector much.
    """
    h = w = IMAGE_SIZE
    yy, xx = np.mgrid[0:h, 0:w].astype(np.int64)

    # Linear congruential dither over the flat pixel index. Integer ops only.
    lcg = ((yy * w + xx) * 1103515245 + SEED) & 0x7FFFFFFF
    dither = (lcg >> 11) & 0x1F

    ramp_x = (xx * 255) // (w - 1)
    ramp_y = (yy * 255) // (h - 1)
    interference = (xx ^ yy) & 0xFF
    checker = (((xx // 32) + (yy // 32)) & 1) * 47

    r = (ramp_x + checker) & 0xFF
    g = (ramp_y + dither) & 0xFF
    b = (interference + checker) & 0xFF

    return np.stack([r, g, b], axis=-1).astype(np.uint8)


def write_synthetic_png(path: str) -> None:
    from PIL import Image

    Image.fromarray(synthetic_image_array(), mode="RGB").save(path, format="PNG")


def embed_synthetic() -> np.ndarray:
    """Embed the synthetic pattern with the production `ClipEmbedder`."""
    from core.embedder import ClipEmbedder

    embedder = ClipEmbedder(MODEL_NAME)
    fd, path = tempfile.mkstemp(suffix=".png", prefix="clip-stability-")
    os.close(fd)
    try:
        write_synthetic_png(path)
        return embedder.image_embedding(path)
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


def _decode_reference() -> np.ndarray:
    raw = base64.b64decode(REFERENCE_B64.encode("ascii"))
    return np.frombuffer(raw, dtype="<f4")


LOAD_MODELS = os.environ.get("CHITRA_TEST_LOAD_MODELS") == "1"


class TestSyntheticImageIsDeterministic(unittest.TestCase):
    """Runs unconditionally — it loads no model."""

    def test_pattern_bytes_are_pinned(self):
        arr = synthetic_image_array()
        self.assertEqual(arr.shape, (IMAGE_SIZE, IMAGE_SIZE, 3))
        self.assertEqual(arr.dtype, np.uint8)
        digest = hashlib.sha256(arr.tobytes()).hexdigest()
        self.assertEqual(
            digest,
            IMAGE_SHA256,
            "the synthetic test pattern changed; the reference vector no longer "
            "describes this image and must be regenerated on the *old* "
            "transformers before any upgrade is judged",
        )

    def test_pattern_has_structure(self):
        # A constant or near-constant image would make the reference vector
        # meaningless as a preprocessing probe.
        arr = synthetic_image_array()
        self.assertGreater(int(arr.std()), 40)
        self.assertEqual(int(arr.min()), 0)
        self.assertEqual(int(arr.max()), 255)

    def test_reference_is_checked_in(self):
        self.assertTrue(
            REFERENCE_B64,
            "REFERENCE_B64 is empty — regenerate it by running this module as a "
            "script on the currently-installed transformers",
        )
        ref = _decode_reference()
        self.assertEqual(ref.shape, (EXPECTED_DIM,))
        self.assertAlmostEqual(float(np.linalg.norm(ref)), 1.0, places=5)


@unittest.skipUnless(
    LOAD_MODELS, "set CHITRA_TEST_LOAD_MODELS=1 to load CLIP (~1.7 GB, ~10 s)"
)
class TestClipEmbeddingIsStable(unittest.TestCase):
    """The safety net for the transformers bump."""

    @classmethod
    def setUpClass(cls):
        cls.vector = embed_synthetic()

    def test_shape_and_norm_unchanged(self):
        self.assertEqual(self.vector.shape, (EXPECTED_DIM,))
        self.assertEqual(self.vector.dtype, np.dtype("float32"))
        self.assertAlmostEqual(float(np.linalg.norm(self.vector)), 1.0, places=5)

    def test_matches_checked_in_reference(self):
        ref = _decode_reference()
        delta = np.abs(self.vector - ref)
        max_delta = float(delta.max())
        cosine = float(np.dot(self.vector, ref))
        self.assertLess(
            max_delta,
            TOLERANCE,
            "CLIP image preprocessing or weights moved: max |delta| "
            f"{max_delta:.3e} (tolerance {TOLERANCE:.0e}), cosine {cosine:.6f}. "
            "Every new embedding now lives in a different space from the ones "
            "already stored. Do NOT relax the tolerance — revert the dependency "
            "change and report, because the alternative is a full re-embed.",
        )

    def test_repeated_embedding_is_reproducible(self):
        """Guards the tolerance itself: run-to-run jitter must be well under it."""
        again = embed_synthetic()
        self.assertLess(float(np.abs(again - self.vector).max()), TOLERANCE / 10)


def _regenerate() -> None:
    import transformers

    arr = synthetic_image_array()
    print(f"image sha256: {hashlib.sha256(arr.tobytes()).hexdigest()}")
    vec = embed_synthetic()
    print(f"transformers: {transformers.__version__}")
    print(f"dim: {vec.shape[0]}  norm: {np.linalg.norm(vec):.8f}")
    print("REFERENCE_B64 = (")
    blob = base64.b64encode(vec.astype("<f4").tobytes()).decode("ascii")
    for i in range(0, len(blob), 76):
        print(f'    "{blob[i:i + 76]}"')
    print(")")


if __name__ == "__main__":
    _regenerate()
