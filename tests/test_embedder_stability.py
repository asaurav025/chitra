"""Pin CLIP's output across a `transformers` upgrade.

Why this test exists
--------------------
`requirements.txt` carried no `transformers` pin at all, and moving the
installed 4.35.0 to >=4.50 crosses the release where `from_pretrained` starts
handing back a **fast** image processor by default instead of the slow PIL one.
Resize filter, rescale order and the resample used for the 224x224 crop all
live on that seam. If any of them shifts, every *new* embedding is computed in
a slightly different space from the ~1,800 vectors already in `embeddings` —
and nothing raises. Search just quietly gets worse, because cosine between a
4.35-era vector and a 4.5x-era vector for the same photo is no longer 1.0.

There is no cheap way to detect that after the fact. So the vector below is
checked in: it is what `ClipEmbedder.image_embedding` returned for a
synthetic image on `transformers==4.35.0`, and it is the thing a dependency
bump has to reproduce.

Reading nothing
---------------
The input image is *generated here*, from integer arithmetic only — no photo,
no MinIO object, no fixture file on disk. `/dev/sda` (which holds all media) is
failing; this test must not depend on it, and it must not depend on a binary
fixture that could be regenerated by accident. Integer-only construction also
means the pixels are bit-identical on any numpy/PIL version, so a mismatch can
only come from the model or its preprocessing, never from the input.

Running it
----------
Gated behind `CHITRA_TEST_LOAD_MODELS=1` so the default suite stays fast and
keeps torch out of the runner:

    CHITRA_TEST_LOAD_MODELS=1 CHITRA_DB_PATH=/tmp/chitra_test.db \
        .venv/bin/python tests/run_tests.py test_embedder_stability

To regenerate the reference (only ever when the *model* is deliberately
changed — never to make a red test green):

    CHITRA_TEST_LOAD_MODELS=1 .venv/bin/python tests/test_embedder_stability.py

**Do not widen `TOLERANCE` to get past a failure.** A failure here means the
stored corpus and future embeddings have diverged, which makes the dependency
bump a forced full re-embed, not a version number.
"""
